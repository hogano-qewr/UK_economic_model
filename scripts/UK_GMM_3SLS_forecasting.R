# A standard NK structural model excels at scenario analysis because it allows you to trace the 
#   shock through specific economic channels—such as energy prices, consumer spending, and 
#   monetary policy—rather than just observing a general downturn.

# Why the 3SLS / NK Model is Suitable for looking at oil price shock (war on Iran):
#   Structural Transmission: You can explicitly model how a rise in oil/gas prices (a "supply shock")
#     hits Inflation Deviation first, which then forces a response in the BOE Rate (Taylor Rule), 
#     ultimately impacting the Output Gap (IS Curve).
#   Simultaneous Feedback: 3SLS is designed to handle the "vicious cycle" where higher inflation 
#     leads to higher interest rates, which then lowers GDP, further impacting unemployment.

# Scenario-Based Forecasting: Use Conditional Forecasting. This involves fixing the path of one 
#   variable (e.g., energy prices) based on a specific crisis scenario and seeing how the 3SLS 
#   system solves for the others.
# Current projections suggest a persistent shock could add 0.3 to 1.2 percentage points to CPI 
#   inflation while cutting GDP growth by 0.2% to 0.9%.
# Expectations & Sentiment: If the crisis is severe, your Inflation Expectations (Infl_exp) might 
#   shift upward as households expect higher long-term costs. You can model this as a structural 
#   break or by adjusting the intercept in your Phillips Curve equation (OBR). 